interface I18nStore {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: keyof typeof dictionaries['pt-BR'], params?: Record<string, string | number>) => string;
}

export const useI18n = create<I18nStore>((set, get) => ({
  lang: (localStorage.getItem('dop_lang') as Language) || 'pt-BR',
  setLang: (lang) => {
    localStorage.setItem('dop_lang', lang);
    set({ lang });
  },
  t: (key, params) => {
    const { lang } = get();
    let text = dictionaries[lang][key] || dictionaries['pt-BR'][key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      });
    }
    return text;
  }
}));
